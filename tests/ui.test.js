import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import fs from 'node:fs/promises';
const tick=()=>new Promise(r=>setTimeout(r,25));
test('complete demo flow: create, edit, search, share, and safe HTML rendering',async()=>{
 const html=await fs.readFile(new URL('../index.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://almohammdin.github.io/afiyah/'});
 globalThis.window=dom.window;globalThis.document=dom.window.document;globalThis.FormData=dom.window.FormData;
 dom.window.scrollTo=()=>{};
 dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true};
 dom.window.HTMLDialogElement.prototype.close=function(){this.open=false};
 await import('../app.js');
 const click=s=>{const el=document.querySelector(s);assert.ok(el,'Missing '+s);el.click()};
 click('[data-act="demo"]');await tick();assert.match(document.body.textContent,/جرعات اليوم/);
 click('[data-view="tasks"]');click('[data-act="add-record"]');
 document.querySelector('[name="name"]').value='<img src=x onerror=alert(1)>';
 document.querySelector('[name="assignee"]').value='فريق الرعاية';
 document.querySelector('[name="date"]').value='2026-10-20';
 click('#editor [type="submit"]');await tick();
 assert.ok(document.body.textContent.includes('<img src=x onerror=alert(1)>'));
 assert.equal(document.querySelector('img[src="x"]'),null);
 click('[data-view="sharing"]');click('[data-act="share"]');
 document.querySelector('[name="email"]').value='relative@example.com';
 const role=document.querySelector('[name="role"]');role.value='custom';role.dispatchEvent(new dom.window.Event('change'));
 document.querySelector('[name="edit_tasks"]').checked=true;
 click('#editor [type="submit"]');await tick();
 assert.match(document.body.textContent,/relative@example.com/);assert.match(document.body.textContent,/بانتظار القبول/);
 click('[data-act="revoke"]');click('[data-act="confirm-revoke"]');await tick();assert.ok(!document.body.textContent.includes('relative@example.com'));
 click('[data-view="patients"]');click('[data-act="add-patient"]');
 document.querySelector('[name="name"]').value='ملف ثان';click('#editor [type="submit"]');await tick();
 assert.match(document.body.textContent,/ملف ثان/);assert.ok(!document.body.textContent.includes('<img src=x onerror=alert(1)>'));
 click('[data-act="logout"]');await tick();assert.match(document.body.textContent,/ابدأ بحساب Google/);
 dom.window.close();
});
